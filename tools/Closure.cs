// Computes game types reachable from PlayerStore/StoreStation that (transitively) hold strings,
// and emits C# that resolves each via typeof(...) / GetNestedType("...") so the mod needs no computed-type reflection.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Mono.Cecil;

// Usage: Closure.exe <Assembly-CSharp.dll> <out.cs> (the output is src/KnownTypes.g.cs).
// Starting from PlayerStore and StoreStation, follows every field type of the game's own save classes and keeps the types
// that reach a string. The store objects listed in skipNames, Unity objects and delegates are not followed; saved inventories
// are JSON text, which JsonText rewrites. Polymorphic fields are covered by also taking the subclasses of each type.
class Closure
{
    static ModuleDefinition mod;
    static Dictionary<TypeDefinition, List<TypeReference>> edges = new Dictionary<TypeDefinition, List<TypeReference>>();
    static HashSet<string> skipNames = new HashSet<string> { "GameItem", "GameInventory", "GameGridInventory", "GameSlotInventory", "GraphNodeStorage", "PixelWindow" };

    static bool IsUnityObject(TypeDefinition t)
    {
        for (var b = t.BaseType; b != null; )
        {
            if (b.FullName == "UnityEngine.Object") return true;
            TypeDefinition bd; try { bd = b.Resolve(); } catch { return false; }
            if (bd == null) return false; b = bd.BaseType;
        }
        return false;
    }
    static bool IsDelegate(TypeDefinition t) { return t.BaseType != null && (t.BaseType.FullName == "System.MulticastDelegate" || t.BaseType.FullName == "System.Delegate"); }

    static IEnumerable<TypeReference> Unwrap(TypeReference tr)
    {
        if (tr.IsArray) { foreach (var x in Unwrap(((ArrayType)tr).ElementType)) yield return x; yield break; }
        var git = tr as GenericInstanceType;
        if (git != null) { foreach (var a in git.GenericArguments) foreach (var x in Unwrap(a)) yield return x; yield break; }
        yield return tr;
    }

    // True for a plain game class worth walking: from this assembly, not generic, enum, interface, Unity object or delegate.
    static bool Mine(TypeReference tr, out TypeDefinition td)
    {
        td = null;
        if (tr.IsGenericParameter) return false;
        try { td = tr.Resolve(); } catch { return false; }
        if (td == null || td.Module != mod || td.HasGenericParameters || td.IsEnum || td.IsInterface) return false;
        if (IsUnityObject(td) || IsDelegate(td) || skipNames.Contains(td.Name)) return false;
        return true;
    }

    static IEnumerable<FieldDefinition> AllFields(TypeDefinition t)
    {
        for (var c = t; c != null && c.Module == mod; )
        {
            foreach (var f in c.Fields) if (!f.IsStatic && !f.IsLiteral) yield return f;
            if (c.BaseType == null) break;
            try { c = c.BaseType.Resolve(); } catch { break; }
        }
    }

    static void Main(string[] a)
    {
        var res = new DefaultAssemblyResolver(); res.AddSearchDirectory(Path.GetDirectoryName(a[0]));
        mod = AssemblyDefinition.ReadAssembly(a[0], new ReaderParameters { AssemblyResolver = res }).MainModule;
        var all = mod.GetTypes().ToList();
        var roots = new[] { "PlayerStore", "StoreStation" }.Select(n => all.First(t => t.FullName == n)).ToList();
        var seen = new HashSet<TypeDefinition>(); var q = new Queue<TypeDefinition>(roots);
        var hasString = new HashSet<TypeDefinition>();
        while (q.Count > 0)
        {
            var t = q.Dequeue(); if (!seen.Add(t)) continue;
            var outs = new List<TypeReference>();
            foreach (var f in AllFields(t))
                foreach (var u in Unwrap(f.FieldType))
                {
                    if (u.FullName == "System.String") hasString.Add(t);
                    TypeDefinition d; if (Mine(u, out d)) { outs.Add(d); q.Enqueue(d); }
                }
            // subclasses (polymorphic fields)
            foreach (var s in all.Where(x => x.BaseType != null && x.BaseType.FullName == t.FullName)) { TypeDefinition d; if (Mine(s, out d)) { outs.Add(d); q.Enqueue(d); } }
            edges[t] = outs;
        }
        // keep types that reach a string
        bool changed = true;
        while (changed) { changed = false; foreach (var t in seen) if (!hasString.Contains(t) && edges[t].Any(o => hasString.Contains(o.Resolve()))) { hasString.Add(t); changed = true; } }

        using (var w = new StreamWriter(a[1]))
        {
            w.WriteLine("// <auto-generated> by tools/Closure.cs from the game's Assembly-CSharp.dll (" + DateTime.Now.ToString("yyyy-MM-dd") + ")");
            w.WriteLine("using System; using System.Collections.Generic; using System.Reflection;");
            w.WriteLine("namespace SaveLanguageConverter {");
            w.WriteLine("// Each GetFields call is made directly on a typeof(...) literal: the game's mod scanner only allows");
            w.WriteLine("// reflection whose receiver it can see is a game type, so the field lists cannot be built in a loop.");
            w.WriteLine("static class KnownTypes {");
            w.WriteLine("  const BindingFlags F = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly;");
            w.WriteLine("  public static Dictionary<Type, FieldInfo[]> All() {");
            w.WriteLine("    var m = new Dictionary<Type, FieldInfo[]>();");
            int ok = 0, skipped = 0;
            foreach (var t in hasString.OrderBy(x => x.FullName))
            {
                string expr = Expr(t);
                if (expr == null || !expr.StartsWith("typeof(")) { w.WriteLine("    // skipped (not nameable with typeof): " + t.FullName); skipped++; continue; }
                w.WriteLine("    m[" + expr + "] = " + expr + ".GetFields(F);"); ok++;
            }
            w.WriteLine("    return m;");
            w.WriteLine("  }");
            w.WriteLine("}}");
            Console.WriteLine("types with strings: " + ok + " emitted, " + skipped + " skipped");
        }
    }

    // The C# expression for a type, or null when it cannot be written as typeof(...) (non-public types). The mod's scanner rejects
    // computed types, so KnownTypes.g.cs must only contain typeof literals.
    static string Expr(TypeDefinition t)
    {
        if (!t.IsNested) return t.IsPublic ? "typeof(global::" + t.FullName.Replace('/', '.') + ")" : null;
        var outer = Expr(t.DeclaringType);
        if (outer == null) return null;
        bool publicChain = t.IsNestedPublic && outer.StartsWith("typeof(");
        if (publicChain) return "typeof(global::" + t.FullName.Replace('/', '.') + ")";
        return "Nested(" + outer + ", \"" + t.Name + "\")";
    }
}
